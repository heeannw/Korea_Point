-- 일본어 커뮤니티 번역에서 지명 바로 뒤에 붙은 중국어 조사 「的」를 「の」로 고친다.
-- 예: 釜山的3泊4日のコース → 釜山の3泊4日のコース, 荒嶺山的夜景 → 荒嶺山の夜景
-- 「基本的」「印象的」처럼 지명이 아닌 낱말과 「釜山的な」 같은 형용사는 건드리지 않는다.
