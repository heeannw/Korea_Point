(function () {
    const root = document.getElementById('headerNotifications');
    if (!root || root.dataset.initialized) return;
    root.dataset.initialized = 'true';
    const bell = root.querySelector('.notification-bell');
    const badge = root.querySelector('.notification-badge');
    const panel = root.querySelector('.notification-panel');
    const list = root.querySelector('.notification-list');
    const status = root.querySelector('.notification-status');
    const more = root.querySelector('.notification-more');
    const readAll = root.querySelector('.notification-read-all');
    const locale = document.documentElement.lang || 'ko';
    let cursor = null, loading = false, mutating = false, unread = 0, counterRequest = false;
    let version = 0;
    const csrfHeaders = {[root.dataset.csrfHeader]: root.dataset.csrfToken};

    function updateCount(count) {
        unread = Number(count) || 0;
        badge.textContent = unread > 99 ? '99+' : String(unread);
        badge.hidden = unread === 0;
        bell.setAttribute('aria-label', root.dataset.title + (unread ? ': ' + root.dataset.countLabel.replace('{0}', unread) : ''));
        readAll.disabled = !unread || mutating;
    }
    function dateLabel(value) {
        const date = new Date(value);
        return Number.isNaN(date.getTime()) ? '' : new Intl.DateTimeFormat(locale, {dateStyle:'short', timeStyle:'short'}).format(date);
    }
    function addText(parent, tag, className, text) {
        const element = document.createElement(tag);
        element.className = className;
        element.textContent = text;
        parent.append(element);
        return element;
    }
    function renderItem(item) {
        const row = document.createElement('li');
        row.className = 'notification-item';
        row.classList.toggle('is-unread', !item.read);
        const link = document.createElement('a');
        // Notification destinations are generated by the server, never supplied by users.
        link.href = item.url;
        addText(link, 'strong', 'notification-item-title', item.title);
        addText(link, 'span', 'notification-place', item.placeTitle);
        addText(link, 'span', 'notification-message', item.message);
        if (item.amount != null) addText(link, 'span', 'notification-payment', root.dataset.amount + ': '
            + new Intl.NumberFormat(locale, {style:'currency', currency:'KRW', maximumFractionDigits:0}).format(item.amount));
        if (item.paymentDeadline) addText(link, 'span', 'notification-payment', root.dataset.deadline + ': ' + dateLabel(item.paymentDeadline));
        const time = addText(link, 'time', 'notification-time', dateLabel(item.createdAt));
        time.dateTime = item.createdAt;
        link.addEventListener('click', async event => {
            if (event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
            event.preventDefault();
            if (mutating || loading) return;
            mutating = true; version++;
            readAll.disabled = true;
            try {
                if (!item.read) {
                    const response = await fetch('/api/notifications/' + item.id + '/read', {method:'PATCH', headers:csrfHeaders});
                    if (!response.ok) throw Error('read failed');
                    item.read = true; row.classList.remove('is-unread');
                    updateCount(Math.max(0, unread - 1));
                }
                window.location.assign(link.href);
            } catch (_) { status.textContent = root.dataset.failed; }
            finally { mutating = false; readAll.disabled = !unread; }
        });
        row.append(link);
        return row;
    }
    async function load(append = false) {
        if (loading || mutating) return;
        loading = true; more.disabled = true;
        status.textContent = root.dataset.loading;
        try {
            const response = await fetch('/api/notifications' + (append && cursor ? '?before=' + cursor : ''), {headers:{Accept:'application/json'}});
            if (!response.ok) throw Error('list failed');
            const data = await response.json();
            if (!append) list.replaceChildren();
            data.items.forEach(item => list.append(renderItem(item)));
            cursor = data.nextCursor;
            more.hidden = cursor == null;
            updateCount(data.unreadCount);
            status.textContent = list.children.length ? '' : root.dataset.empty;
        } catch (_) { status.textContent = root.dataset.failed; }
        finally { loading = false; more.disabled = false; }
    }
    async function refreshCount() {
        if (document.hidden || counterRequest || mutating || loading) return;
        const requestVersion = version;
        counterRequest = true;
        try {
            const response = await fetch('/api/notifications/unread-count', {headers:{Accept:'application/json'}});
            if (response.ok) {
                const data = await response.json();
                if (requestVersion === version) {
                    const changed = Number(data.count) !== unread;
                    updateCount(data.count);
                    if (changed && !panel.hidden && list.scrollTop === 0) load();
                }
            }
        } catch (_) { /* Keep the last known count; opening the panel offers a retry. */ }
        finally { counterRequest = false; }
    }
    window.closeHeaderNotifications = function () { panel.hidden = true; bell.setAttribute('aria-expanded', 'false'); };
    bell.addEventListener('click', () => {
        if (!panel.hidden) { window.closeHeaderNotifications(); return; }
        window.closeHeaderMenus?.();
        panel.hidden = false; bell.setAttribute('aria-expanded', 'true');
        if (window.innerWidth <= 600) panel.style.top = (bell.getBoundingClientRect().bottom + 10) + 'px';
        version++;
        load();
    });
    root.querySelector('.notification-close').addEventListener('click', () => { window.closeHeaderNotifications(); bell.focus(); });
    document.addEventListener('click', event => { if (!root.contains(event.target)) window.closeHeaderNotifications(); });
    document.addEventListener('keydown', event => {
        if (event.key === 'Escape' && !panel.hidden) { window.closeHeaderNotifications(); bell.focus(); }
    });
    more.addEventListener('click', () => load(true));
    readAll.addEventListener('click', async () => {
        if (mutating || loading) return;
        mutating = true; version++; readAll.disabled = true;
        try {
            const response = await fetch('/api/notifications/read-all', {method:'PATCH', headers:csrfHeaders});
            if (!response.ok) throw Error('read all failed');
            mutating = false;
            updateCount(0);
            await load();
        } catch (_) { status.textContent = root.dataset.failed; }
        finally { mutating = false; readAll.disabled = !unread; }
    });
    document.addEventListener('visibilitychange', refreshCount);
    window.addEventListener('focus', refreshCount);
    setInterval(refreshCount, 30000);
    refreshCount();
})();
